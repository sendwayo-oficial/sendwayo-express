const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '..', 'SENDWAYO-EXPRESS-V7-CORREGIDO-DOP-BALANCES-COMISIONES-AVISOS.html'), 'utf8');
const start = html.indexOf('<div id="welcome-landing"');
assert.ok(start >= 0, 'la portada pública debe existir');
const welcome = html.slice(start, start + 1200);
assert.match(welcome, /src="assets\/sendwayo-logo-real\.jpg"/, 'el logo corporativo debe aparecer primero');
assert.match(welcome, /class="sendwayo-landing-title">SENDWAYO EXPRESS/, 'el nombre del negocio debe ir debajo del logo');
assert.match(welcome, /id="sendwayo-home-login"[^>]*>INGRESAR/, 'el único botón debe ser Ingresar');
assert.doesNotMatch(welcome, /sendwayo-home-register|REGISTRAR/, 'Registrar no debe aparecer en la portada');
assert.doesNotMatch(welcome, /sendwayo-landing-photo-panel|sendwayo-welcome-only-photo/, 'la portada no debe mostrar otras fotos');
assert.ok(welcome.indexOf('sendwayo-landing-logo') < welcome.indexOf('sendwayo-landing-title'), 'el logo debe aparecer antes del nombre');
assert.ok(welcome.indexOf('sendwayo-landing-title') < welcome.indexOf('sendwayo-home-login'), 'Ingresar debe aparecer debajo del nombre');
assert.match(html, /sendwayo-v7-minimal-welcome-final/, 'la portada debe usar el diseño vertical compacto');
assert.match(html, /width:124px!important;height:88px!important/, 'el logo debe ser compacto');
assert.match(html, /function openLogin\(\)/, 'Ingresar debe tener un controlador');
assert.match(html, /loginButton\.addEventListener\('click'/, 'Ingresar debe tener un evento activo');
assert.match(html, /window\.v162_showLogin\(\)/, 'Ingresar debe abrir el formulario de acceso real');
assert.match(html, /href="assets\/sendwayo-tailwind\.css"/, 'la página debe servir Tailwind desde su propio sitio');
assert.doesNotMatch(html, /https:\/\/cdn\.tailwindcss\.com/, 'la portada no debe depender del CDN externo');
assert.doesNotMatch(html, /body:not\(\.sendwayo-authenticated\)>#sendwayo-v7-modal/, 'el modal de registro no debe cubrir la portada');
console.log('PASS: portada vertical compacta, logo pequeño, nombre del negocio y único botón Ingresar.');
