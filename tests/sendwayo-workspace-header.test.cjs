const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const html = fs.readFileSync(path.join(__dirname, '..', 'SENDWAYO-EXPRESS-V7-CORREGIDO-DOP-BALANCES-COMISIONES-AVISOS.html'), 'utf8');
assert.match(html, /id="sendwayo-brand-bar"/, 'barra superior');
assert.match(html, /id="sendwayo-v7-business-name"[^>]*>SENDWAYO EXPRESS/, 'nombre comercial');
assert.match(html, /id="sendwayo-v7-user-strip"/, 'identidad en cabecera');
assert.match(html, /id="sendwayo-v7-name"/, 'nombre de cuenta');
assert.match(html, /id="sendwayo-v7-role"/, 'rol');
assert.match(html, /id="sendwayo-v7-id"/, 'ID');
assert.match(html, /id="sendwayo-v7-date"/, 'fecha');
assert.match(html, /id="sendwayo-v7-clock"/, 'hora');
assert.match(html, /id="sendwayo-v7-duration"/, 'duración de sesión');
assert.doesNotMatch(html, /Código:|Cód\.:|id="sendwayo-v7-code"/, 'ningún código debe mostrarse');
assert.match(html, /function refreshIdentity\(\)/, 'controlador de identidad');
const refreshIdentity = html.match(/function refreshIdentity\(\)\{[\s\S]*?\n \}/)?.[0] || '';
assert.match(refreshIdentity, /'sendwayo-v7-name':isAdmin\?'ADMINISTRADOR'/, 'el administrador debe mostrarse como ADMINISTRADOR');
assert.match(refreshIdentity, /'sendwayo-v7-id':isAdmin\?'ADMIN-ADMINISTRADOR'/, 'el ID administrativo debe ser el oficial');
assert.match(html, /id="sendwayo-main-content"/, 'contenedor principal');
assert.match(html, /id="sendwayo-mobile-menu"/, 'un botón de menú');
assert.equal((html.match(/id="sendwayo-mobile-menu"/g)||[]).length,1,'solo un botón hamburguesa');
assert.match(html, /id="sendwayo-top-logout"/, 'salir en la cabecera');
assert.match(html, /#sendwayo-v7-user-strip\{display:flex!important;flex-flow:row nowrap!important/s, 'identidad en una sola línea');
assert.match(html, /#sendwayo-v7-user-strip \.sendwayo-workspace-person,[^{}]*\{[^}]*flex-direction:row!important/s, 'nombre, rol e ID horizontales');
assert.match(html, /#sendwayo-v7-user-strip \.sendwayo-workspace-time\s*\{[^}]*flex-direction:row!important/s, 'fecha, hora y duración horizontales');
assert.match(html, /#sendwayo-main-sidebar\{display:block!important;position:relative!important/s, 'menú de módulos visible a la izquierda en escritorio');
assert.match(html, /sendwayo-v7-header-one-line-runtime/, 'controlador de cabecera única');
assert.doesNotMatch(html, /sendwayo-v7-top-only-workspace-controller/, 'sin segundo controlador de identidad');
assert.doesNotMatch(html, /sendwayo-v7-unified-workspace-header/, 'sin segunda hoja de cabecera');
assert.doesNotMatch(html, /sendwayo-v7-top-only-workspace-layout/, 'sin hoja de distribución contradictoria');
console.log('SENDWAYO workspace header: identidad y navegación en una sola línea verificadas.');
